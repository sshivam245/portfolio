/**
 * Writes scripts/tokens.mjs into every consumer, or checks that it already is.
 *
 *   npm run tokens        rewrite globals.css and the figure SVGs
 *   npm run tokens:check  fail if any consumer has drifted (runs in prebuild)
 *
 * Consumers:
 *   1. src/app/globals.css   — the :root / .dark blocks, between sentinels
 *   2. public/figures/*.svg  — the <style> block each file carries
 *   3. scripts/og.mjs        — imports TOKENS directly, nothing to write
 *
 * The SVGs keep a real style block rather than inheriting from the page,
 * because Figure.tsx and FigureHero.tsx serve figures through <img>, where no
 * external stylesheet can reach inside. Only diagram figures are inlined.
 * Generating the block is what makes one source possible without breaking
 * the <img> path.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { TOKENS, SVG_CLASSES } from "./tokens.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const drift = [];

/** Replace the region between two sentinel comments, exclusive. */
function spliceSentinels(text, open, close, body, where) {
  const a = text.indexOf(open);
  const b = text.indexOf(close);
  if (a === -1 || b === -1 || b < a)
    throw new Error(`${where}: sentinels ${open} / ${close} not found`);
  return text.slice(0, a + open.length) + body + text.slice(b);
}

const decls = (t, indent) =>
  Object.entries(t)
    .map(([k, v]) => `${indent}${k}: ${v};`)
    .join("\n");

// ---------------------------------------------------------------- globals.css
{
  const file = path.join(root, "src/app/globals.css");
  const before = fs.readFileSync(file, "utf8");
  const body = `
  :root {
${decls(TOKENS.light, "    ")}
  }

  .dark {
${decls(TOKENS.dark, "    ")}
  }
`;
  const after = spliceSentinels(
    before,
    "/* tokens:start — generated by scripts/sync-tokens.mjs, do not edit */",
    "  /* tokens:end */",
    body,
    "globals.css",
  );
  if (after !== before) {
    drift.push("src/app/globals.css");
    if (!check) fs.writeFileSync(file, after);
  }
}

// ------------------------------------------------------------- figure SVGs
{
  const dir = path.join(root, "public/figures");
  const light = SVG_CLASSES(TOKENS.light);
  const dark = SVG_CLASSES(TOKENS.dark);

  // The dark override only restates what actually changes; .box and .rule
  // share a stroke, so they collapse to one selector exactly as the
  // hand-written blocks did.
  const block = `  <style>
${Object.entries(light)
  .map(([sel, rule]) => `    ${sel.padEnd(6)} { ${rule} }`)
  .join("\n")}
    text   { font-family: var(--font-plex-mono, "IBM Plex Mono"), ui-monospace, monospace; }
    .lbl   { font-size: 10px; letter-spacing: 0.08em; }
    .sub   { font-size: 9px; }
    .tiny  { font-size: 8px; }
    @media (prefers-color-scheme: dark) {
      .ink   { ${dark[".ink"]} }
      .muted { ${dark[".muted"]} }
      .accf  { ${dark[".accf"]} }
      .acc   { ${dark[".acc"]} }
      .box, .rule { stroke: ${TOKENS.dark["--rule"]}; }
    }
  </style>`;

  for (const name of fs.readdirSync(dir).filter((f) => f.endsWith(".svg"))) {
    const file = path.join(dir, name);
    const before = fs.readFileSync(file, "utf8");
    const m = before.match(/ {2}<style>[\s\S]*?<\/style>/);
    if (!m) throw new Error(`${name}: no <style> block to replace`);
    const after = before.replace(m[0], block);
    if (after !== before) {
      drift.push(`public/figures/${name}`);
      if (!check) fs.writeFileSync(file, after);
    }
  }
}

// ----------------------------------------------- consumers that must not drift
{
  const og = fs.readFileSync(path.join(root, "scripts/og.mjs"), "utf8");
  // Its own vendored font paths and numeric literals are fine; colour is not.
  const hexes = og.match(/#[0-9a-fA-F]{6}\b/g);
  if (hexes) drift.push(`scripts/og.mjs holds colour literals: ${[...new Set(hexes)].join(", ")}`);
}

{
  // --ink-b is 2.8:1 on light stock. Enforce the documented rule: it never
  // carries small text in light mode. A dark:-prefixed utility is fine.
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.tsx?$/.test(e.name)) {
        const src = fs.readFileSync(p, "utf8").split("\n");
        src.forEach((line, i) => {
          // text-ink-b is legal only behind a dark: prefix.
          if (/(^|[^:\w-])text-ink-b\b/.test(line))
            out.push(`${path.relative(root, p)}:${i + 1}  ${line.trim()}`);
        });
      }
    }
  };
  walk(path.join(root, "src"));
  if (out.length)
    drift.push(`--ink-b used as light-mode text (2.8:1):\n    ${out.join("\n    ")}`);
}

if (!drift.length) {
  console.log(check ? "tokens: all consumers in sync" : "tokens: nothing to write");
  process.exit(0);
}
if (check) {
  console.error("tokens: out of sync with scripts/tokens.mjs\n  " + drift.join("\n  "));
  console.error("\nRun `npm run tokens`.");
  process.exit(1);
}
console.log("tokens: wrote\n  " + drift.join("\n  "));
